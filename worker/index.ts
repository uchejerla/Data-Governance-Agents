import { createFreebuffAuth, isSameOriginRequest } from '@freebuff/auth';
import type { FreebuffAuth, FreebuffUser } from '@freebuff/auth';
import { evaluateLicence, hasModule, summarise, type Entitlement } from './licence';
import { applyMigrations, SCHEMA_VERSION } from './migrations';
import { D1DecisionStore, type DecisionStore } from './storage';
import { APP_VERSION } from './version';

// Shared steward decisions API.
//
// Every signed-in steward sees the same backlog: one row per recommendation,
// with who recorded the current decision and when. Every change is also appended
// to an event log, so the history of a decision survives later overwrites.
//
// The schema is migrated on first use rather than by an out-of-band command: the
// platform gives the Worker a database binding, not a SQL console. All SQL lives
// behind `DecisionStore`, so the routes below never see a column name.

export interface Env {
  ASSETS: { fetch(request: Request): Promise<Response> };
  DB: D1Database;
  FREEBUFF_CLIENT_ID: string;
  FREEBUFF_ISSUER?: string;
  APP_ORIGIN: string;
  /** Signed licence token (compact JWS). Absent means evaluation mode. */
  LICENCE_KEY?: string;
  /** SPKI public key (base64url) that verifies LICENCE_KEY. Never the private key. */
  LICENCE_PUBLIC_KEY?: string;
  /** Optional key id; when set, the licence header must name it. */
  LICENCE_KEY_ID?: string;
  /** "true" turns a missing licence into a read-only install instead of an evaluation. */
  LICENCE_REQUIRED?: string;
}

type Status = 'accepted' | 'dismissed';

// Recommendation keys are generated by the app (asset id + gap id, rule id,
// request id, term issue id). They are printable ASCII and bounded in length.
const KEY_PATTERN = /^[\x21-\x7E](?:[\x20-\x7E]{0,158}[\x21-\x7E])?$/;
const ASSIGNEE_PATTERN = /^[\x21-\x7E]{1,64}$/;
const MAX_BODY_BYTES = 2048;
const DEFAULT_HISTORY_LIMIT = 200;
const MAX_HISTORY_LIMIT = 500;
const STATUSES: Status[] = ['accepted', 'dismissed'];

const HEADERS = {
  'Content-Type': 'application/json; charset=utf-8',
  // Personalized data must never be cached by a shared cache.
  'Cache-Control': 'private, no-store',
};

// Security headers on every response, assets and auth redirects included — a page
// that is framed or sniffed is as exposed as one that leaks a stack trace.
//
// The CSP is the strict default for this app: same-origin scripts, no framing, no
// plugins, forms back to ourselves. Inline styles are allowed because React writes
// `style` attributes; a change that needs a new origin has to widen this on purpose.
const SECURITY_HEADERS: Record<string, string> = {
  'Content-Security-Policy': [
    "default-src 'self'",
    "script-src 'self'",
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data:",
    "font-src 'self'",
    "connect-src 'self'",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ].join('; '),
  // Ignored by browsers on a plain-http origin, so local development is unaffected.
  'Strict-Transport-Security': 'max-age=31536000; includeSubDomains',
  'X-Content-Type-Options': 'nosniff',
  // Legacy companion to frame-ancestors for clients that do not read CSP.
  'X-Frame-Options': 'DENY',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
  'Permissions-Policy': 'camera=(), microphone=(), geolocation=()',
};

/**
 * Copy a response so the security headers can be added without losing what the
 * route set (content type, cache control, and the session cookie on a sign-in).
 * A 204 or 304 must not carry a body, and a Response constructed with a stream for
 * one of those throws.
 */
function withSecurityHeaders(response: Response): Response {
  const headers = new Headers(response.headers);
  for (const [name, value] of Object.entries(SECURITY_HEADERS)) headers.set(name, value);
  const body = response.status === 204 || response.status === 304 ? null : response.body;
  return new Response(body, {
    status: response.status,
    statusText: response.statusText,
    headers,
  });
}

function json(body: unknown, status = 200): Response {
  return new Response(JSON.stringify(body), { status, headers: HEADERS });
}

let auth: FreebuffAuth | undefined;
let handler: ((request: Request, env: Env) => Promise<Response>) | undefined;
let handlerEnv: Env | undefined;
let schemaReady: Promise<void> | undefined;
let entitlementPromise: Promise<Entitlement> | undefined;

function getAuth(env: Env): FreebuffAuth {
  auth ??= createFreebuffAuth({
    clientId: env.FREEBUFF_CLIENT_ID,
    issuer: env.FREEBUFF_ISSUER,
    baseUrl: env.APP_ORIGIN,
    // Loopback development only; the deployed origin is https and never sets this.
    allowInsecureLocalhost: /^http:\/\/(localhost|127\.0\.0\.1|\[::1\])(:\d+)?$/.test(env.APP_ORIGIN),
  });
  return auth;
}

// Verification is deterministic for a given configuration, so it runs once per
// isolate rather than on every request. Changing the licence means a redeploy.
function getEntitlement(env: Env): Promise<Entitlement> {
  entitlementPromise ??= evaluateLicence({
    token: env.LICENCE_KEY,
    publicKey: env.LICENCE_PUBLIC_KEY,
    keyId: env.LICENCE_KEY_ID,
    required: /^(true|1)$/i.test(env.LICENCE_REQUIRED ?? ''),
  });
  return entitlementPromise;
}

function ensureSchema(env: Env): Promise<void> {
  schemaReady ??= applyMigrations(env.DB).catch((error: unknown) => {
    // Let a later request retry rather than failing forever on a cold database.
    schemaReady = undefined;
    throw error;
  });
  return schemaReady;
}

function displayName(user: FreebuffUser): string {
  const name = user.name?.trim();
  if (name) return name;
  const email = user.email?.trim();
  if (email) return email;
  return 'Signed-in steward';
}

async function readBody(request: Request): Promise<Record<string, unknown> | null> {
  const text = await request.text();
  if (text.length === 0 || text.length > MAX_BODY_BYTES) return null;
  try {
    const parsed: unknown = JSON.parse(text);
    if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) return null;
    return parsed as Record<string, unknown>;
  } catch {
    return null;
  }
}

async function listDecisions(store: DecisionStore): Promise<Response> {
  return json({ decisions: await store.listDecisions() });
}

// The append-only log behind every decision. It is the record of *who* changed
// what and when, including decisions that were later overwritten or withdrawn.
//
// Pages descend by event id (`before`), newest first. The cursor keeps paging
// stable while other stewards are writing: a new event at the top can never shift
// a page boundary and duplicate or skip a row.
async function listHistory(store: DecisionStore, url: URL): Promise<Response> {
  const parsed = Number(url.searchParams.get('limit') ?? DEFAULT_HISTORY_LIMIT);
  const limit = Number.isFinite(parsed)
    ? Math.min(MAX_HISTORY_LIMIT, Math.max(1, Math.trunc(parsed)))
    : DEFAULT_HISTORY_LIMIT;

  const beforeRaw = url.searchParams.get('before');
  const before = beforeRaw === null ? null : Number(beforeRaw);
  if (before !== null && (!Number.isInteger(before) || before <= 0)) {
    return json({ error: 'before must be a positive event id' }, 400);
  }

  const events = await store.listEvents({ limit, before });
  return json({
    events,
    // A full page may be the end of the log; the client's next request returns
    // empty and stops. Null here means this page was short, so nothing follows.
    nextBefore: events.length === limit ? events[events.length - 1].id : null,
  });
}

async function upsertDecision(
  store: DecisionStore,
  user: FreebuffUser,
  key: string,
  request: Request,
): Promise<Response> {
  const body = await readBody(request);
  if (!body) return json({ error: 'Expected a small JSON object body' }, 400);

  const status = body.status;
  if (typeof status !== 'string' || !STATUSES.includes(status as Status)) {
    return json({ error: 'status must be "accepted" or "dismissed"' }, 400);
  }
  const assigneeRaw = body.assigneeId;
  let assigneeId: string | null = null;
  if (assigneeRaw !== undefined && assigneeRaw !== null && assigneeRaw !== '') {
    if (typeof assigneeRaw !== 'string' || !ASSIGNEE_PATTERN.test(assigneeRaw)) {
      return json({ error: 'assigneeId is not a valid person id' }, 400);
    }
    assigneeId = assigneeRaw;
  }

  const decision = await store.recordDecision({
    key,
    status: status as Status,
    assigneeId,
    actor: { id: user.sub, name: displayName(user), email: user.email ?? null },
    at: new Date().toISOString(),
  });
  return json({ decision });
}

async function deleteDecision(
  store: DecisionStore,
  user: FreebuffUser,
  key: string,
): Promise<Response> {
  const existing = await store.findDecision(key);
  if (!existing) return json({ error: 'No decision recorded for that item' }, 404);
  if (existing.updatedBy !== user.sub) {
    return json(
      { error: `Only ${existing.updatedByName ?? 'the steward who recorded it'} can withdraw this decision` },
      403,
    );
  }

  await store.withdrawDecision({
    key,
    actor: { id: user.sub, name: displayName(user), email: user.email ?? null },
    at: new Date().toISOString(),
  });

  return json({ cleared: key });
}

async function handleApi(request: Request, env: Env, store: DecisionStore): Promise<Response> {
  const authClient = getAuth(env);
  const url = new URL(request.url);

  if (url.pathname === '/api/decisions' && request.method === 'GET') {
    const user = await authClient.getUser(request);
    if (!user) return json({ error: 'Sign in required' }, 401);
    return listDecisions(store);
  }

  if (url.pathname === '/api/decisions/history' && request.method === 'GET') {
    // The log carries actor identities, so it is as private as the backlog.
    const user = await authClient.getUser(request);
    if (!user) return json({ error: 'Sign in required' }, 401);
    // The audit trail is a package feature, enforced here rather than in the UI.
    if (!hasModule(await getEntitlement(env), 'audit-export')) {
      return json({ error: 'The audit trail is not included in this licence' }, 403);
    }
    return listHistory(store, url);
  }

  const match = /^\/api\/decisions\/([^/]+)$/.exec(url.pathname);
  if (match && (request.method === 'PUT' || request.method === 'DELETE')) {
    // Reject forged cross-origin writes before doing any work.
    if (!isSameOriginRequest(request, env.APP_ORIGIN)) {
      return json({ error: 'Cross-origin request refused' }, 403);
    }
    // Read-only is an installation state, not a user permission: no write from
    // anyone should reach the database once the licence has lapsed.
    const entitlement = await getEntitlement(env);
    if (entitlement.readOnly) {
      return json({ error: entitlement.reason ?? 'This installation is read-only' }, 403);
    }

    const user = await authClient.getUser(request);
    if (!user) return json({ error: 'Sign in required' }, 401);

    let key: string;
    try {
      key = decodeURIComponent(match[1]);
    } catch {
      return json({ error: 'Malformed item key' }, 400);
    }
    if (!KEY_PATTERN.test(key)) return json({ error: 'Malformed item key' }, 400);

    return request.method === 'PUT'
      ? upsertDecision(store, user, key, request)
      : deleteDecision(store, user, key);
  }

  return json({ error: 'Not found' }, 404);
}

async function route(request: Request, env: Env): Promise<Response> {
  const url = new URL(request.url);

  // Liveness and version for a probe or an operator. Both are public because a
  // probe has no session, so neither may carry a binding name, a licence or a
  // customer: the version, the schema id and whether the database answered.
  if (url.pathname === '/api/health' && request.method === 'GET') {
    const database = await new D1DecisionStore(env.DB).ping();
    return json(
      {
        status: database ? 'ok' : 'degraded',
        version: APP_VERSION,
        schema: SCHEMA_VERSION,
        database: database ? 'ok' : 'unavailable',
      },
      database ? 200 : 503,
    );
  }

  if (url.pathname === '/api/version' && request.method === 'GET') {
    return json({ version: APP_VERSION, schema: SCHEMA_VERSION });
  }

  if (url.pathname === '/api/licence' && request.method === 'GET') {
    // Public: a banner about expiry is useful before anyone signs in, and this
    // carries no customer identity — only status, modules and limits.
    return json({ licence: summarise(await getEntitlement(env)) });
  }

  if (url.pathname === '/api/me') {
    const user = await getAuth(env).getUser(request);
    if (!user) return json({ error: 'Sign in required' }, 401);
    return json({
      user: {
        id: user.sub,
        name: displayName(user),
        email: user.email ?? null,
        picture: user.picture ?? null,
      },
    });
  }

  if (url.pathname.startsWith('/api/')) {
    // Any API call may need the schema, including a signed-out one that only
    // gets a 401 — so a cold deployment is ready before the first write.
    await ensureSchema(env);
    return handleApi(request, env, new D1DecisionStore(env.DB));
  }

  return env.ASSETS.fetch(request);
}

export default {
  async fetch(request: Request, env: Env): Promise<Response> {
    const authClient = getAuth(env);
    if (handlerEnv !== env) {
      // One wrapped handler per isolate: auth caches discovery and signing keys.
      handler = authClient.wrap((req: Request, innerEnv: Env) => route(req, innerEnv));
      handlerEnv = env;
    }
    try {
      return withSecurityHeaders(await handler!(request, env));
    } catch (error) {
      // Internals go to the platform log; the client gets a generic body so a stack
      // trace, a SQL string or a binding name never reaches the browser.
      console.error('Unhandled request error', error);
      return withSecurityHeaders(json({ error: 'Something went wrong' }, 500));
    }
  },
};
